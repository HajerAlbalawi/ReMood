// ── Detect book language from city name ───────────────────────────────────────
export function getCityBookLang(cityName: string): Lang {
  // Arabic-speaking cities
  if (/الرياض|جدة|مكة|المدينة|الدمام|أبها|حائل|تبوك|الطائف|الأحساء|أبوظبي|دبي|الكويت|المنامة|الدوحة|مسقط|بغداد|دمشق|عمّان|بيروت|القدس|القاهرة|الإسكندرية|طرابلس|تونس|الجزائر|الرباط|الدار البيضاء|الخرطوم|نواكشوط/.test(cityName)) return "ar";
  // French-speaking cities
  if (/باريس|بروكسل|لوكسمبرغ|جنيف|أبيدجان|داكار|نيامي|واغادوغو|بانجي|ياوندي|لومي|كينشاسا|برازافيل|بانجول|بيساو|موروني|جيبوتي|نجامينا/.test(cityName)) return "fr";
  // Default → English (covers UK, USA, Asia, Europe, Latin America, etc.)
  return "en";
}

